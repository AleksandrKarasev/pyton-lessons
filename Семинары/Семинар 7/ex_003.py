"""
Задача Nº51. Решение задачи
Напишите функцию same_by(characteristic, objects), которая проверяет, 
все ли объекты имеют одинаковое значение некоторой характеристики, 
и возвращают True, если это так.
Если значение характеристики для разных объектов отличается - то False. 
Для пустого набора объектов, функция должна возвращать True. 
Аргумент characteristic - это функция, которая принимает объект 
и вычисляет его характеристику.
Ввод:
Вывод:
values = [0, 2, 10, 6]
same
if same_by(lambda x: x % 2, values):
print('same')
else:
print('different')
"""

def same_by(characteristic, objects):
    """
    Проверяет, все ли объекты имеют одинаковое значение характеристики.
    
    Args:
        characteristic: функция, принимающая объект и возвращающая его характеристику.
        objects: итерируемый объект (список, кортеж и т.д.).
        
    Returns:
        True, если все характеристики одинаковы или список пуст, иначе False.
    """
    # Создаём множество уникальных характеристик
    unique = {characteristic(obj) for obj in objects}
    # Если характеристик не более одной, возвращаем True
    return len(unique) <= 1


# Демонстрация из условия задачи
values = [0, 2, 10, 6]
if same_by(lambda x: x % 2, values):
    print('same')
else:
    print('different')

# Дополнительная проверка для пустого списка
print(same_by(lambda x: x % 2, []))  # True