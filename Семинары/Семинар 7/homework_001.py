"""
Задача 34: Винни-Пух попросил Вас посмотреть, есть ли в его стихах ритм. 
Поскольку разобраться в его кричалках не настолько просто, насколько легко 
он их придумывает, Вам стоит написать программу. 
Винни-Пух считает, что ритм есть, если число слогов 
(т.е. число гласных букв) в каждой фразе стихотворения одинаковое. 
Фраза может состоять из одного слова, если во фразе несколько слов, 
то они разделяются дефисами. Фразы отделяются друг от друга пробелами. 
Стихотворение Винни-Пух вбивает в программу с клавиатуры. 
В ответе напишите "Парам пам-пам", если с ритмом все в порядке и "Пам парам",
если с ритмом все не в порядке
"""

def count_vowels(phrase):
    """Подсчитывает количество гласных букв в фразе."""
    vowels = "аеёиоуыэюя"
    return sum(1 for char in phrase.lower() if char in vowels)

def check_rhythm(poem):
    """
    Проверяет, есть ли ритм в стихотворении Винни-Пуха.
    Возвращает "Парам пам-пам", если количество гласных во всех фразах одинаково,
    иначе "Пам парам".
    """
    phrases = poem.split()  # фразы разделены пробелами
    if not phrases:
        return "Парам пам-пам"  # пустое стихотворение — ритм есть

    # Вычисляем количество гласных в каждой фразе
    vowels_counts = [count_vowels(phrase) for phrase in phrases]

    # Проверяем, все ли значения одинаковы
    if all(count == vowels_counts[0] for count in vowels_counts):
        return "Парам пам-пам"
    else:
        return "Пам парам"

# Ввод стихотворения с клавиатуры и вывод результата
poem_input = input("Введите стихотворение Винни-Пуха: ")
result = check_rhythm(poem_input)
print(result)